-- ----------------------------
-- 中国省市区表 core_china_region (仅省市级数据)
-- ----------------------------
drop table if exists core_china_region;
create table core_china_region
(
    id          bigint(20)  not null auto_increment comment '主键ID',
    code        varchar(20) not null comment '行政区划代码',
    name        varchar(50) not null comment '地区名称',
    parent_code varchar(20) default '0' comment '父级行政区划代码（省级为0）',
    level       tinyint(1)  not null comment '层级（1省/直辖市/自治区 2市 3区/县）',
    pinyin      varchar(100) default null comment '拼音',
    full_name   varchar(100) default null comment '全称',
    longitude   decimal(10, 7) default null comment '经度',
    latitude    decimal(10, 7) default null comment '纬度',
    sort_order  int(11)     default 0 comment '排序',
    status      char(1)     default '0' comment '状态（0正常 1停用）',
    create_time datetime    default current_timestamp comment '创建时间',
    update_time datetime    default current_timestamp on update current_timestamp comment '更新时间',
    primary key (id),
    unique key uk_code (code),
    key idx_parent_code (parent_code),
    key idx_level (level)
) engine = innodb auto_increment = 1 comment = '中国省市区表';

